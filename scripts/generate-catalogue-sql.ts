// Generates the catalogue seed migration and the all-in-one setup SQL from
// src/model/catalogue.ts. Run: npm run gen:catalogue-sql
import { readFileSync, writeFileSync } from 'node:fs';
import { CATALOGUE_VERSION, PROFILE_WEIGHTS, QUESTIONS } from '../src/model/catalogue';

const lit = (s: string) => `'${s.replace(/'/g, "''")}'`;
const json = (v: unknown) => `${lit(JSON.stringify(v))}::jsonb`;

export function catalogueSql(): string {
  const rows = QUESTIONS.map((q) => `  (${[
    lit(q.id), lit(CATALOGUE_VERSION), lit(q.domain), q.localWeight, lit(q.route), lit(q.name), lit(q.base.question), q.chapter + 1, lit(q.statusType),
    json(q.base.anchors), lit(q.evidence), json(q.contributors), q.naAllowed ? 'true' : 'false',
  ].join(', ')})`);
  const weights = Object.entries(PROFILE_WEIGHTS).flatMap(([p, ws]) => Object.entries(ws).map(([d, w]) => `  (${lit(CATALOGUE_VERSION)}, ${lit(p)}, ${lit(d)}, ${w})`));
  return `-- GENERATED by \`npm run gen:catalogue-sql\` from src/model/catalogue.ts. Do not edit by hand.
insert into public.question_definitions
  (id, catalogue_version, domain, local_weight, route, name, question, chapter, status_type, anchors, evidence, contributors, na_allowed)
values
${rows.join(',\n')};

insert into public.profile_weights (catalogue_version, profile, domain, weight)
values
${weights.join(',\n')};
`;
}

const seed = catalogueSql();
writeFileSync('supabase/migrations/20261124120100_seed_catalogue_v2.sql', seed);
const schema = readFileSync('supabase/migrations/20261124120000_init_schema_v2.sql', 'utf8');
writeFileSync('supabase/setup-all-in-one.sql', `-- ExitIQ v2: complete database setup for a NEW Supabase project.
-- Paste into the SQL Editor and run once. Runs as one transaction and stops
-- without changes if the tables already exist.
begin;
${schema}
${seed}
commit;
`);
console.log(`Wrote seed (${QUESTIONS.length} questions) and supabase/setup-all-in-one.sql`);
